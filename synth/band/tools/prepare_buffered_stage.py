"""Add complete-frame display reads to the spectrum stage variant."""
from pathlib import Path
import subprocess,sys
b=Path(__file__).resolve().parents[1]
subprocess.run([sys.executable,str(b/'tools/prepare_spectrum_stage.py')],check=True)
s=(b/'experimental/audio_visual/band_stage_spectrum_top.sv').read_text()
def change(old,new):
 global s
 assert s.count(old)==1,old
 s=s.replace(old,new)
change('module band_stage_spectrum_top #(', 'module band_stage_buffered_top #(')
change('input wire analysis_clk,spectrum_ready,output wire spectrum_valid,\n output wire[10:0]spectrum_bin,',
 '''input wire analysis_clk,display_clk,display_read,display_release,input wire[10:0]display_address,
 output wire display_available,spectrum_valid,output wire[31:0]rejected_bins,
 ''')
change('pcm_spectrum #(', 'pcm_spectrum_buffered #(')
change('.audio_clk(clk),.analysis_clk(analysis_clk),', '.audio_clk(clk),.analysis_clk(analysis_clk),.display_clk(display_clk),')
change('.spectrum_valid(spectrum_valid),\n .spectrum_ready(spectrum_ready),.spectrum_bin(spectrum_bin),.spectrum_real(spectrum_real),.spectrum_imag(spectrum_imag),\n .spectrum_frame(spectrum_frame),.spectrum_last_sample(spectrum_last_sample),',
 '''.read_enable(display_read),.read_address(display_address),.release_frame(display_release),
 .frame_available(display_available),.read_valid(spectrum_valid),.read_real(spectrum_real),.read_imag(spectrum_imag),
 .frame_number(spectrum_frame),.last_sample(spectrum_last_sample),.rejected_bins(rejected_bins),''')
(b/'experimental/audio_visual/band_stage_buffered_top.sv').write_text('// GENERATED by prepare_buffered_stage.py; physical display/timing pending.\n'+s)
